def render_md() -> str:
    L = ["# " + TITLE, "", "> " + SUBTITLE, "", LEDE, "",
         "*이 문서는 `_build_qna.py` 가 생성한다. 본문을 고치려면 그 스크립트의 `PARTS` 를 고친다.*", ""]
    n = 0
    for part in PARTS:
        first = n + 1
        last = n + len(part["items"])
        L += ["---", "",
              "## " + part["eyebrow"] + " — " + part["title"] + "  (Q%d–Q%d)" % (first, last),
              "", "*" + part["note"] + "*", ""]
        for item in part["items"]:
            n += 1
            L += ["### Q%d. %s" % (n, item["q"]), ""]
            prev_bullet = False
            for para in item["a"]:
                is_bullet = para.startswith("- ")
                if is_bullet:
                    L.append(para)
                else:
                    if prev_bullet:
                        L.append("")     # 리스트가 문단을 삼키지 않게
                    L += [para, ""]
                prev_bullet = is_bullet
            if L[-1] != "":
                L.append("")
            if item.get("link"):
                L += ["> 🔗 " + item["link"], ""]
    return "\n".join(L).rstrip() + "\n"


