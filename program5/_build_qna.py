def check() -> int:
    items = list(numbered())
    assert len(items) == 100, "문항 총수가 100 이 아니다: %d" % len(items)
    assert [n for n, _, _ in items] == list(range(1, 101)), "번호가 연속이 아니다"
    for n, part, item in items:
        assert item["q"].endswith("?"), "Q%d 질문이 물음표로 끝나지 않는다" % n
        assert item["a"], "Q%d 답이 비어 있다" % n
    print("✅ 100문 · 번호 1–100 연속 · 파트 %d개" % len(PARTS))
    for i, part in enumerate(PARTS):
        print("   %-8s %-28s %2d문" % (part["eyebrow"], part["title"], len(part["items"])))
    return 0


def main(argv) -> int:
    if "--check" in argv:
        return check()
    check()
    if "--fragment" in argv:
        dest = Path(argv[argv.index("--fragment") + 1])
        dest.write_text(HEAD + render_body() + "\n", encoding="utf-8")
        print("✅ %s" % dest)
        return 0
    MD_OUT.write_text(render_md(), encoding="utf-8")
    HTML_OUT.write_text(render_html(), encoding="utf-8")
    print("✅ %s (%.1f KB)" % (MD_OUT.name, MD_OUT.stat().st_size / 1024))
    print("✅ %s (%.1f KB)" % (HTML_OUT.name, HTML_OUT.stat().st_size / 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
