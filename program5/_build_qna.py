def numbered():
    """(번호, 파트, 항목) 을 1..100 으로 흘려 준다."""
    n = 0
    for part in PARTS:
        for item in part["items"]:
            n += 1
            yield n, part, item


def esc(s: str) -> str:
    return html.escape(s, quote=False)


_BOLD = re.compile(r"\*\*(.+?)\*\*")
_CODE = re.compile(r"`(.+?)`")


def inline(s: str) -> str:
    """**굵게** 와 `코드` 만 처리한다. 그 외는 이스케이프된 평문."""
    out = esc(s)
    out = _CODE.sub(lambda m: "<code>" + m.group(1) + "</code>", out)
    out = _BOLD.sub(lambda m: "<strong>" + m.group(1) + "</strong>", out)
    return out


